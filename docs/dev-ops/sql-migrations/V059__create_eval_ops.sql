CREATE TABLE IF NOT EXISTS `ai_eval_dataset` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `dataset_id` VARCHAR(64) NOT NULL,
  `name` VARCHAR(255) NOT NULL,
  `description` TEXT DEFAULT NULL,
  `execution_mode` VARCHAR(32) NOT NULL DEFAULT 'INDEPENDENT' COMMENT 'INDEPENDENT/SCENARIO',
  `owner_user_id` VARCHAR(128) NOT NULL DEFAULT '10001',
  `status` VARCHAR(32) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/ARCHIVED',
  `latest_version_no` INT NOT NULL DEFAULT 0,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_eval_dataset_id` (`dataset_id`),
  KEY `idx_eval_dataset_owner` (`owner_user_id`, `updated_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='EvalOps logical datasets';

CREATE TABLE IF NOT EXISTS `ai_eval_dataset_version` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `version_id` VARCHAR(64) NOT NULL,
  `dataset_id` VARCHAR(64) NOT NULL,
  `version_no` INT NOT NULL,
  `status` VARCHAR(32) NOT NULL COMMENT 'DRAFT/PUBLISHED',
  `description` TEXT DEFAULT NULL,
  `case_count` INT NOT NULL DEFAULT 0,
  `evaluator_version` VARCHAR(64) NOT NULL DEFAULT 'agent-rules-v1',
  `evaluator_config_json` MEDIUMTEXT DEFAULT NULL,
  `checksum` VARCHAR(64) DEFAULT NULL,
  `published_at` DATETIME(3) DEFAULT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_eval_version_id` (`version_id`),
  UNIQUE KEY `uk_eval_dataset_version_no` (`dataset_id`, `version_no`),
  KEY `idx_eval_version_status` (`dataset_id`, `status`),
  CONSTRAINT `fk_eval_version_dataset` FOREIGN KEY (`dataset_id`)
    REFERENCES `ai_eval_dataset` (`dataset_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Immutable published dataset versions and editable draft';

CREATE TABLE IF NOT EXISTS `ai_eval_case` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `case_id` VARCHAR(64) NOT NULL,
  `version_id` VARCHAR(64) NOT NULL,
  `stable_key` VARCHAR(128) NOT NULL,
  `sequence_no` INT NOT NULL,
  `conversation_group` VARCHAR(128) NOT NULL DEFAULT 'default',
  `category` VARCHAR(128) DEFAULT NULL,
  `tags_json` TEXT DEFAULT NULL,
  `question` MEDIUMTEXT NOT NULL,
  `config_json` MEDIUMTEXT NOT NULL,
  `reference_answer` MEDIUMTEXT DEFAULT NULL,
  `enabled` TINYINT(1) NOT NULL DEFAULT 1,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_eval_case_id` (`case_id`),
  UNIQUE KEY `uk_eval_case_stable` (`version_id`, `stable_key`),
  KEY `idx_eval_case_order` (`version_id`, `conversation_group`, `sequence_no`),
  CONSTRAINT `fk_eval_case_version` FOREIGN KEY (`version_id`)
    REFERENCES `ai_eval_dataset_version` (`version_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Versioned evaluation cases';

CREATE TABLE IF NOT EXISTS `ai_eval_run` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `eval_run_id` VARCHAR(64) NOT NULL,
  `dataset_id` VARCHAR(64) NOT NULL,
  `version_id` VARCHAR(64) NOT NULL,
  `version_no` INT NOT NULL,
  `name` VARCHAR(255) NOT NULL,
  `status` VARCHAR(32) NOT NULL COMMENT 'QUEUED/RUNNING/RULE_COMPLETED/JUDGING/COMPLETED/FAILED/CANCELLED',
  `execution_mode` VARCHAR(32) NOT NULL,
  `user_id` VARCHAR(128) NOT NULL,
  `tenant_id` VARCHAR(128) NOT NULL DEFAULT 'default',
  `selected_agent_id` VARCHAR(64) DEFAULT NULL,
  `memory_policy` VARCHAR(32) NOT NULL DEFAULT 'ISOLATED_USER',
  `concurrency` INT NOT NULL DEFAULT 1,
  `evaluator_version` VARCHAR(64) NOT NULL,
  `config_snapshot_json` MEDIUMTEXT DEFAULT NULL,
  `total_cases` INT NOT NULL DEFAULT 0,
  `completed_cases` INT NOT NULL DEFAULT 0,
  `passed_cases` INT NOT NULL DEFAULT 0,
  `failed_cases` INT NOT NULL DEFAULT 0,
  `rule_score` DECIMAL(7,4) DEFAULT NULL,
  `judge_score` DECIMAL(7,2) DEFAULT NULL,
  `started_at` DATETIME(3) DEFAULT NULL,
  `finished_at` DATETIME(3) DEFAULT NULL,
  `error_message` TEXT DEFAULT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_eval_run_id` (`eval_run_id`),
  KEY `idx_eval_run_dataset` (`dataset_id`, `created_at`),
  KEY `idx_eval_run_status` (`status`, `created_at`),
  CONSTRAINT `fk_eval_run_dataset` FOREIGN KEY (`dataset_id`)
    REFERENCES `ai_eval_dataset` (`dataset_id`),
  CONSTRAINT `fk_eval_run_version` FOREIGN KEY (`version_id`)
    REFERENCES `ai_eval_dataset_version` (`version_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='EvalOps evaluation runs';

