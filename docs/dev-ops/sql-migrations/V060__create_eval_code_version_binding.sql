CREATE TABLE IF NOT EXISTS `ai_eval_code_version` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `eval_run_id` VARCHAR(64) NOT NULL,
  `repository_name` VARCHAR(255) DEFAULT NULL,
  `branch_name` VARCHAR(255) DEFAULT NULL,
  `captured_head_sha` VARCHAR(64) DEFAULT NULL,
  `captured_tags_json` TEXT DEFAULT NULL,
  `dirty` TINYINT(1) NOT NULL DEFAULT 0,
  `source_tree_hash` VARCHAR(64) DEFAULT NULL COMMENT 'Filtered Git tree hash of the running source snapshot',
  `hash_algorithm` VARCHAR(32) NOT NULL DEFAULT 'GIT_TREE_SHA1',
  `scope_version` VARCHAR(32) NOT NULL DEFAULT 'evalops-v1',
  `ignore_rules_json` MEDIUMTEXT DEFAULT NULL,
  `snapshot_json` MEDIUMTEXT DEFAULT NULL,
  `binding_status` VARCHAR(32) NOT NULL DEFAULT 'WAITING_TAG' COMMENT 'WAITING_TAG/AUTO_VERIFIED/MANUAL_VERIFIED/MANUAL_UNVERIFIED/CAPTURE_UNAVAILABLE',
  `bound_tag` VARCHAR(255) DEFAULT NULL,
  `bound_commit_sha` VARCHAR(64) DEFAULT NULL,
  `matched_tags_json` TEXT DEFAULT NULL,
  `binding_method` VARCHAR(32) DEFAULT NULL,
  `binding_note` VARCHAR(1000) DEFAULT NULL,
  `bound_at` DATETIME(3) DEFAULT NULL,
  `last_checked_at` DATETIME(3) DEFAULT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_eval_code_version_run` (`eval_run_id`),
  KEY `idx_eval_code_version_status` (`binding_status`, `created_at`),
  KEY `idx_eval_code_version_tag` (`bound_tag`),
  CONSTRAINT `fk_eval_code_version_run` FOREIGN KEY (`eval_run_id`)
    REFERENCES `ai_eval_run` (`eval_run_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='EvalOps immutable code snapshot and post-hoc Git tag binding';
