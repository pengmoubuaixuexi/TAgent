-- V048 (2026-06-16): 给【分析步】系统提示开 ask_user 例外，让 D 段「LLM 主动问用户」能在分析步真正触发。
--
-- 背景：D 段把 ask_user 工具广播到非执行步（含分析步），但 V044/V045 给这些步的系统提示写了
-- "禁止调用任何工具" → 模型守规矩，即使 ask_user 在请求 schema 里也不调，只把问题写成文字分析。
-- 实测 8012_p1 成都游：模型 reasoning 里明说"该先跟用户确认预算/人数/偏好"，却没发 ask_user tool_call。
--
-- 修法：仅给【分析步】(8012_p1 auto / 8013_p1 flow) 把"禁止调用任何工具"改成"禁止调用任何工具，
-- ask_user 除外（ask_user 是向用户澄清的手段、不视为执行工具）"。
-- 措辞【工具无关】：不枚举任何具体工具名/类别（不写搜索/地图/查询等），避免绑死当前 MCP 工具集。
-- 质检/汇总/规划步【不动】：那些步不该问用户，ask_user 虽被广播但提示仍禁→模型不调（harmless）。
--
-- 本文件自愈幂等：每个 prompt 同时 REPLACE「原始 V044/V045 文案」和「本迁移早期中间版文案（曾枚举
-- 搜索/地图/查询，已废弃）」→ 最终工具无关文案。任何 DB 状态重跑都收敛到同一结果，且到达终态后为 no-op。
-- 改 DB 提示后需重启应用。

